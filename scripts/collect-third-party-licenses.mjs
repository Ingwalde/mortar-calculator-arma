// Collect notices from installed runtime packages without changing their licenses.
// Run after npm ci and before every build; optional native packages vary by platform.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const packages = new Map();
const missing = [];

function locate(name, from) {
  for (let dir = from; ; dir = dirname(dir)) {
    const candidate = join(dir, "node_modules", name, "package.json");
    if (existsSync(candidate)) return dirname(candidate);
    if (dir === dirname(dir)) return null;
  }
}

function visit(name, from, optional = false) {
  const dir = locate(name, from);
  if (!dir) {
    if (!optional) throw new Error(`Missing runtime dependency: ${name}`);
    return;
  }
  if (packages.has(dir)) return;
  const info = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const files = readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && /^(licen[sc]e|copying|copyright|notice|third[-_]party[-_]notices)([._-]|$)/i.test(entry.name))
    .map((entry) => entry.name).sort();
  // sharp's native component inventory is supplied in README.md, not LICENSE.
  if (name.startsWith("@img/sharp") && existsSync(join(dir, "README.md"))) files.push("README.md");
  const supplemental = join(root, "legal/npm", `${info.name.replaceAll("/", "_")}@${info.version}.txt`);
  if (!files.length && !existsSync(supplemental)) missing.push(`${info.name}@${info.version}`);
  packages.set(dir, { info, files, supplemental });
  const optionalNames = info.optionalDependencies ?? {};
  for (const child of Object.keys({ ...info.dependencies, ...optionalNames }).sort()) {
    visit(child, dir, Object.hasOwn(optionalNames, child));
  }
}

for (const name of Object.keys(pkg.dependencies).sort()) visit(name, root);
// These packages are build dependencies but their code is shipped in mobile/web apps.
for (const name of ["@capacitor/core", "@capacitor/app", "@capacitor/browser", "@capacitor/android"]) visit(name, root);
if (missing.length) throw new Error(`Packages without notice files: ${missing.join(", ")}`);

const entries = [...packages.entries()].sort(([a], [b]) => {
  const x = relative(root, a).replaceAll("\\", "/");
  const y = relative(root, b).replaceAll("\\", "/");
  return x < y ? -1 : x > y ? 1 : 0;
});
const sections = [
  "Installed runtime package notices",
  "Generated by scripts/collect-third-party-licenses.mjs from the current npm installation.",
  "This inventory covers JavaScript packages and their supplied notice files, not a complete native-binary audit.",
  "Some entries are used only by desktop or Android builds; optional native packages depend on the build host.",
  "Electron/Chromium and Android transitive native dependencies require their separate notices.",
  "For sharp native source and release requirements, see legal/NATIVE-COMPONENTS.md.",
  "node-forge is used under its BSD-3-Clause option; retaining its upstream license file does not select GPL.",
  ""
];
for (const [dir, { info, files, supplemental }] of entries) {
  sections.push("=".repeat(72), `${info.name}@${info.version}`, `Declared license: ${info.license ?? "See package notices"}`);
  for (const file of files) sections.push(`\n--- ${file} ---\n`, readFileSync(join(dir, file), "utf8"));
  if (existsSync(supplemental)) sections.push("\n--- Supplemental package notice ---\n", readFileSync(supplemental, "utf8"));
}
const output = resolve(root, "resources/legal/npm-notices.txt");
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, sections.join("\n") + "\n");
console.log(`Collected ${entries.length} package notices into resources/legal/npm-notices.txt`);
